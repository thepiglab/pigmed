"""Multi-node launcher for train_s1 (S1.5): renders a Slurm batch script that starts one torchrun per node via srun
(c10d rendezvous on the first node), so N nodes x G GPUs form one world; negatives are shared within a node
(--gather-group, default one node) and gradients are averaged over nodes (dist_utils).

It never submits. It writes the script and prints the submit command; site specifics (account, partition, the
env file that defines PIGMED_ROOT / PIGMED_CODE, the submit wrapper) are arguments, so nothing site-specific lives
in the repo.

    python -m eg2late.launch --name s1.5-a --nodes 4 --gpus-per-node 8 --account ACCT --partition PART \\
        --env-sh /path/env.sh --out-script job.sbatch --dry-run -- --mix-config configs/s1_5_mix.json

--dry-run also runs `train_s1 --dry-run` locally with the same trainer flags (argument and mix-config validation,
nothing loaded) and prints the world layout and a wall-time / GPU-hour estimate.
"""
from __future__ import annotations

import argparse
import json
import shlex
import subprocess
import sys
from pathlib import Path

TEMPLATE = """#!/usr/bin/env bash
# Generated by eg2late.launch: {nodes} node(s) x {gpn} GPU(s), gather group {group}, run {name}
#SBATCH --job-name=pigmed-train-eg2late-{name}-{nodes}n{gpn}g
#SBATCH --account={account}
#SBATCH --qos={qos}
#SBATCH --partition={partition}
#SBATCH --nodes={nodes}
#SBATCH --ntasks-per-node=1
#SBATCH --gpus-per-node={gpn}
#SBATCH --cpus-per-task={cpus}
#SBATCH --mem={mem}
#SBATCH --time={time}
#SBATCH --output={logdir}/{name}-%j.log
set -euo pipefail
ulimit -c 0
source {env_sh}
module load {cuda_module} >/dev/null 2>&1 || true
T=$PIGMED_ROOT/train; V=$T/venv; E=$PIGMED_ROOT/embed-rs
export HF_HUB_OFFLINE=1 TOKENIZERS_PARALLELISM=false PYTHONPATH=$PIGMED_CODE/train TMPDIR=$T/tmp PYTHONNOUSERSITE=1 \\
  TORCHINDUCTOR_CACHE_DIR=$T/tmp/inductor TRITON_CACHE_DIR=$T/tmp/triton OMP_NUM_THREADS=1 NCCL_DEBUG=WARN
SG=$(python3 -c "import json;print(json.load(open('$E/models.json'))['google/embeddinggemma-2']['path'])")
O=$T/runs/{name}; mkdir -p $O
HEAD=$(scontrol show hostnames "$SLURM_JOB_NODELIST" | head -n1)
echo "nodes: $SLURM_JOB_NODELIST head: $HEAD"
srun --kill-on-bad-exit=1 --ntasks-per-node=1 bash -c "ulimit -c 0; cd $PIGMED_CODE/train && \\
  $V/bin/torchrun --nnodes=$SLURM_NNODES --nproc_per_node={gpn} --rdzv_id=$SLURM_JOB_ID --rdzv_backend=c10d \\
  --rdzv_endpoint=$HEAD:{port} -m eg2late.train_s1 --base $SG --data $T/data --out $O --workers {workers} \\
  --gather-group {group} {targs}"
du -sh $O
"""


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True)
    ap.add_argument("--nodes", type=int, default=1)
    ap.add_argument("--gpus-per-node", type=int, default=8)
    ap.add_argument("--gather-group", type=int, default=0, help="0 = one node")
    ap.add_argument("--account", default="ACCOUNT")
    ap.add_argument("--qos", default=None, help="default: = account")
    ap.add_argument("--partition", default="PARTITION")
    ap.add_argument("--cpus-per-gpu", type=int, default=4)
    ap.add_argument("--mem-per-gpu", type=int, default=40, help="GB")
    ap.add_argument("--time", default="24:00:00")
    ap.add_argument("--env-sh", default="$HOME/env.sh", help="file defining PIGMED_ROOT / PIGMED_CODE")
    ap.add_argument("--logdir", default="$PIGMED_ROOT/train/logs")
    ap.add_argument("--cuda-module", default="cuda")
    ap.add_argument("--port", type=int, default=29500)
    ap.add_argument("--workers", type=int, default=3)
    ap.add_argument("--submit-cmd", default="sbatch", help="printed, never run (e.g. a site wrapper)")
    ap.add_argument("--out-script", type=Path, default=None)
    ap.add_argument("--s-per-step", type=float, default=10.0, help="for the estimate (RTX PRO 6000, 128 q/GPU)")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("trainer", nargs=argparse.REMAINDER, help="-- then train_s1 flags")
    a = ap.parse_args(argv)
    targs = [x for x in a.trainer if x != "--"]
    W = a.nodes * a.gpus_per_node
    group = a.gather_group or a.gpus_per_node
    if W % group:
        sys.exit(f"world {W} is not a multiple of the gather group {group}")
    script = TEMPLATE.format(
        nodes=a.nodes, gpn=a.gpus_per_node, group=group, name=a.name, account=a.account, qos=a.qos or a.account,
        partition=a.partition, cpus=a.cpus_per_gpu * a.gpus_per_node, mem=f"{a.mem_per_gpu * a.gpus_per_node}G",
        time=a.time, logdir=a.logdir, env_sh=a.env_sh, cuda_module=a.cuda_module, port=a.port, workers=a.workers,
        targs=" ".join(shlex.quote(x) for x in targs))
    if a.out_script:
        a.out_script.write_text(script)
    resolved = None
    if a.dry_run:
        r = subprocess.run([sys.executable, "-m", "eg2late.train_s1", "--base", "X", "--data", "X", "--out", "X",
                            "--dry-run", *targs], capture_output=True, text=True, cwd=Path(__file__).resolve().parents[1])
        if r.returncode:
            sys.exit(f"trainer flags rejected:\n{r.stderr[-2000:]}")
        resolved = json.loads(r.stdout)
        steps, B = int(resolved["steps"] or 0), int(resolved["batch"])
        per_rank = steps  # train_s1: `steps` total plan entries x world, split over ranks -> `steps` per rank
        hours = per_rank * a.s_per_step / 3600
        print(json.dumps({
            "world": W, "gather_group": group, "groups": W // group,
            "queries_per_step": B * W, "queries_per_group_step": B * group,
            "docs_per_group_step": B * group * (1 + int(resolved["n_neg"])),
            "steps_per_rank": per_rank, "queries_total": per_rank * B * W,
            "est_wall_h": round(hours, 1), "est_gpu_h": round(hours * W, 1),
            "sources": resolved["sources"], "mix": resolved["mix"]}, indent=1))
    if not a.out_script:
        print(script)
    print(f"# submit: {a.submit_cmd} -A {a.account} --qos={a.qos or a.account} {a.out_script or '<script>'}")
    return resolved


if __name__ == "__main__":
    main()
